function onPreRadioChange(radioName, optIdx, cardId) {
  participantState.rawRadios[radioName] = optIdx;
  const card = document.getElementById(cardId);
  if (card) card.classList.remove("border-rose-400", "bg-rose-50/50");
  updatePreCounter();
  syncTestAnswersToState();
  saveProgress();
}

function updatePreCounter() {
  let count = 0;
  preHabitsQuestions.forEach(item => {
    if (document.querySelector(`input[name="pre_habit_${item.id}"]:checked`)) count++;
  });
  knowledgeTopics.forEach((_, idx) => {
    if (document.querySelector(`input[name="pre_know_${idx}"]:checked`)) count++;
  });
  const counterEl = document.getElementById("preProgressCounter");
  if (counterEl) counterEl.textContent = `${count} из 24`;
}

function syncTestAnswersToState() {
  preHabitsQuestions.forEach(item => {
    const checked = document.querySelector(`input[name="pre_habit_${item.id}"]:checked`);
    if (checked) {
      participantState.preHabitsAnswers[item.id] = {
        score: parseInt(checked.value, 10),
        tag: checked.dataset.tag || ""
      };
    }
  });

  knowledgeTopics.forEach((topic, idx) => {
    const checkedPre = document.querySelector(`input[name="pre_know_${idx}"]:checked`);
    if (checkedPre) {
      const optIdx = parseInt(checkedPre.value, 10);
      participantState.preKnowledgeAnswers[idx] = {
        selectedIdx: optIdx,
        isCorrect: topic.preOptions[optIdx].correct
      };
    }

    const checkedPost = document.querySelector(`input[name="post_know_${idx}"]:checked`);
    if (checkedPost) {
      const optIdx = parseInt(checkedPost.value, 10);
      participantState.postKnowledgeAnswers[idx] = {
        selectedIdx: optIdx,
        isCorrect: topic.postOptions[optIdx].correct
      };
    }
  });

  postReflectionQuestions.forEach(item => {
    const checkedRef = document.querySelector(`input[name="post_ref_${item.id}"]:checked`);
    if (checkedRef) {
      participantState.postReflectAnswers[item.id] = {
        score: parseInt(checkedRef.value, 10),
        goalCode: checkedRef.dataset.goal || "",
        text: checkedRef.dataset.text || ""
      };
    }
  });
}

