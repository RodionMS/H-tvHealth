function submitPreTest() {
  let allAnswered = true;
  let firstMissed = null;

  preHabitsQuestions.forEach(item => {
    const checked = document.querySelector(`input[name="pre_habit_${item.id}"]:checked`);
    const card = document.getElementById(`pre-habit-card-${item.id}`);
    if (!checked) {
      allAnswered = false;
      card.classList.add("border-rose-400", "bg-rose-50/50");
      if (!firstMissed) firstMissed = card;
    } else {
      card.classList.remove("border-rose-400", "bg-rose-50/50");
    }
  });

  knowledgeTopics.forEach((_, idx) => {
    const checked = document.querySelector(`input[name="pre_know_${idx}"]:checked`);
    const card = document.getElementById(`pre-know-card-${idx}`);
    if (!checked) {
      allAnswered = false;
      card.classList.add("border-rose-400", "bg-rose-50/50");
      if (!firstMissed) firstMissed = card;
    } else {
      card.classList.remove("border-rose-400", "bg-rose-50/50");
    }
  });

  const errBox = document.getElementById("preTestError");
  if (!allAnswered) {
    errBox.classList.remove("hidden");
    if (firstMissed) firstMissed.scrollIntoView({ behavior: "smooth", block: "center" });
    return;
  }

  errBox.classList.add("hidden");
  syncTestAnswersToState();
  goToStep(3);
}

