function saveProgress() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(participantState));
  } catch (e) {}
}

function handleNameInput(val) {
  participantState.name = val.trim();
  updateNamePlaceholders(participantState.name || "Коллега");
  saveProgress();
}

function restoreSavedProgress() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return;
    const saved = JSON.parse(raw);
    if (!saved) return;

    participantState = Object.assign(participantState, saved);

    if (participantState.name) {
      const nameInput = document.getElementById("participantName");
      if (nameInput) nameInput.value = participantState.name;
      updateNamePlaceholders(participantState.name);
    }

    if (participantState.rawRadios) {
      Object.keys(participantState.rawRadios).forEach(radioName => {
        const optIdx = participantState.rawRadios[radioName];
        const radios = document.querySelectorAll(`input[name="${radioName}"]`);
        if (radios && radios[optIdx]) {
          radios[optIdx].checked = true;
        }
      });
    }

    updatePreCounter();
    updatePostCounter();

    const step = participantState.currentStep || 1;
    if (step === 6) {
      buildFinalResultsScreen(true);
    }
    goToStep(step, false);
  } catch (e) {
    localStorage.removeItem(STORAGE_KEY);
  }
}

function resetSavedProgress() {
  if (confirm("Очистить сохраненные ответы и начать прохождение с первого этапа?")) {
    localStorage.removeItem(STORAGE_KEY);
    window.location.reload();
  }
}

function updateNamePlaceholders(name) {
  document.querySelectorAll(".user-name-placeholder").forEach(el => {
    el.textContent = name;
  });
}

